/**
 * 回答（id -> 0..1 の同意度）から種族の重心を作る。
 *
 * 遺伝子ごとに「符号つきの重み平均」を取る。1問だけ極端でも、同じ遺伝子に効く
 * 他の問いと平均されるので飛ばない。逆転項目があるので、全部同意は中央に落ちる。
 */
export function centroidFrom(answers) {
  const num = {}, den = {};
  for (const q of STATEMENTS) {
    const a = answers[q.id];
    if (a == null) continue;
    const signed = (a - 0.5) * 2;            // -1(強く反対) .. +1(強く同意)
    for (const g in q.w) {
      const w = q.w[g];
      num[g] = (num[g] ?? 0) + Math.sign(w) * signed * Math.abs(w);
      den[g] = (den[g] ?? 0) + Math.abs(w);
    }
  }
  const c = {};
  for (const g of MIND_GENES) {
    const d = den[g] || 0;
    c[g] = d ? clamp01(0.5 + SPAN * (num[g] / d)) : 0.5;
  }
  return normalizeArms(c);
}

/**
 * 心系だけで出来ている染色体（4・5・6・7）に、sim と同じ対抗アーム予算を掛ける。
 *
 * ここが**双極尺度の本体**。軸の位置は絶対値ではなく「A側の得点 − B側の得点」で決まる。
 * 予算で割ると、その差だけが残って和は必ず1.0になるので、
 *
 *   両側に同意した人 → 差がゼロ → 全部0.5＝軸の中央
 *   片側に寄った人   → 差がそのまま残る（例 A=0.9,0.9 / B=0.1,0.1 は和が1.0なので無変更）
 *   両側に反対した人 → やはり差だけが残る
 *
 * になる。実際の性格検査が双極尺度を使うのと同じ理由で、これをやらずに絶対値で
 * 採点すると、sim 側の正規化（mean(A)+mean(B)=1 の**等式**）に当たった瞬間に
 * 6軸が全部0.5へ潰れて型が決まらない。
 *
 * 和を1.0に揃えて渡すので、sim 側の正規化はこの4本については何もしない（＝要求が通る）。
 * 2番・3番は体系遺伝子と同居していて予算の分母が違うので sim 側に任せる。
 * 8番は対抗アームではない（ARM_EXEMPT）ので触らない。振れ幅と向きは独立に立つ。
 */
function normalizeArms(c) {
  for (const ax of AXES) {
    if (!ax.b.length) continue;                    // 8番＝独立座位。予算はない
    const A = ax.a, B = ax.b;
    const s = mean(A.map(g => c[g])) + mean(B.map(g => c[g]));
    if (s <= 1e-6) { for (const g of [...A, ...B]) c[g] = 0.5; continue; }
    const k = 1 / s;
    for (const g of [...A, ...B]) c[g] = clamp01(c[g] * k);
  }
  return c;
}

const mean = (xs) => (xs.length ? xs.reduce((s, x) => s + x, 0) / xs.length : 0);

/** 6軸のスコア。-1（B側に振り切り）… +1（A側に振り切り）。 */
export function axisScores(centroid) {
  return AXES.map(ax => {
    const av = mean(ax.a.map(g => centroid[g] ?? 0.5));
    const score = ax.b.length
      ? clamp(av - mean(ax.b.map(g => centroid[g] ?? 0.5)), -1, 1)
      : clamp((av - 0.5) * 2, -1, 1);
    const side = score >= 0 ? 0 : 1;
    return {
      ...ax, score, side, letter: ax.code[side],
      // どちら側かだけでなく「どれだけ寄っているか」。MBTIの 51% / 88% と同じ役割で、
      // 中央付近の軸を「振り切った軸」と同じ顔で見せないために要る。
      strength: Math.round(50 + Math.abs(score) * 50),
      weak: Math.abs(score) < 0.12,
    };
  });
}

