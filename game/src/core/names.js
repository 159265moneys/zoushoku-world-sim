/** 世界内で重複しない名前を配る。尽きたら二つ名を足して延命する。 */
export class NameGiver {
  constructor(rng) {
    this.rng = rng;
    this.used = new Set(FOUNDERS);
    this.pool = rng.shuffle([...new Set(NAME_POOL)]);
    this.i = 0;
    this.suffix = 0;
  }
  take() {
    while (this.i < this.pool.length) {
      const n = this.pool[this.i++];
      if (!this.used.has(n)) { this.used.add(n); return n; }
    }
    // 二周目以降は世代名を付ける（ミカエル二世、三世…）
    this.suffix++;
    this.i = 0;
    const kanji = ['','二','三','四','五','六','七','八','九','十'];
    const tag = kanji[Math.min(this.suffix, 9)] + '世';
    const n = this.rng.pick(this.pool) + tag + (this.suffix > 9 ? String(this.suffix) : '');
    this.used.add(n);
    return n;
  }
}
