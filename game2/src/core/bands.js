// レア度の帯（正典2-4）── ★ `stats.js` だけに依存させる。
//   genetics.js に置くと people.js → condition.js → genetics.js → people.js の循環になる
import * as S from './stats.js';

export const SCALE = 100;
// ===========================================================================
// 正典2-4　レア度の帯　★2026-08-31 に実装（M-40 が「採用」と書いてから入っていなかった）
// ===========================================================================
// > **レア度は、そのステが出やすい帯。N F E D C B A の7段。**
// > **8割ちょっとは帯の中に落ちる。残りは帯の外へ出るが、帯から遠いほど出にくい。**
// > **だから全レア度で1も100も出る。だが帯が低いレア度ほど、高い値は出にくい。**
// > **帯に落ちる割合 85%／裾の広さ 30.4。合計106**
//
// ★ 正典2-4 は「85%＋τ30.4」と書きながら、同じ節の表の D・B の裾がそれより約2倍薄い。
//   正典7658 が「**帯を実装するときに、表とパラメータを1度だけ突き合わせて片方に寄せること**」
//   と指示している。**パラメータに寄せた。**理由3つ：
//     (1) 正典が「規則」として書いているのはパラメータで、表はその帰結
//     (2) 台帳 M-40 の「採用」がパラメータ（85%＋τ30.4）で測っている
//     (3) τ=30.4 は M-39 が表のA行「80以上＝1.00%」から逆算した値 ＝ 表が
//         自己整合している所に錨が打ってある
// ★★ 既定オフ（2026-08-31）★★
//   帯そのものは正典2-4 のとおりに組めて、レア度別の**平均・中央・106ステ全体の平均45.4
//   （台帳M-40 は45.9）が表と一致する**。だが入れると世界が死ぬ ── 106ステのうち
//   **77個（D/C/B/A）の帯が50より下**にあるので、「才能50が中央」で校正された
//   **読み手を全部貼り直さないと**、全員が虚弱になる（実測：300年7種で絶滅 1→4、平均人口 600→88）。
//   寿命・老いの速さ・繁殖力・病への強さ・傷の治り・疲労・必要睡眠 までは貼り直したが、
//   婚姻の相性・狩りの当たり・戦闘・評判 などが残っている。**専用の1回で全部やる。**
//   ★ オフのときは `bandNorm(s,v) = v/100`・`BAND_MID = 50`・`ARM_BUDGET_OF = 100` になり、
//     帯を入れる前と**1ビットも変わらない**（貼り直した読み手も元の式に戻る）。
//   ★ **`process` を直に書かない**（Node にしか無いのでブラウザではモジュール評価で落ちる。
//     2026-08-31 に world.js の SPLIT_FIELDS で実際に画面が真っ黒になった）。
//     切替えは globalThis 経由で読む ── ブラウザなら `globalThis.BAND = 1` でも入る
const ENV = (typeof process !== 'undefined' && process && process.env) ? process.env : {};
export const BAND_ON = ENV.BAND === '1' || globalThis.BAND === 1;
export const BAND_IN = 0.85, BAND_TAU = 30.4;
export const RARITY_BAND = {
  N: [50, 82], F: [44, 77], E: [38, 72], D: [31, 66], C: [24, 60], B: [15, 53], A: [1, 45],
};
export const BAND_LO = new Float32Array(S.COUNT);
export const BAND_HI = new Float32Array(S.COUNT);
export const BAND_MID = new Float32Array(S.COUNT);
for (let i = 0; i < S.COUNT; i++) {
  const b = BAND_ON ? (RARITY_BAND[S.RARITY_LEVELS[S.RARITY[i]]] ?? [1, SCALE]) : [0, SCALE];
  BAND_LO[i] = b[0]; BAND_HI[i] = b[1]; BAND_MID[i] = (b[0] + b[1]) / 2;
}
/**
 * 帯から才能を1つ引く。85% は帯の中の一様、15% は帯の外へ exp(−d/30.4) で薄くなる裾。
 * ★ 上下対称に出して 1..100 で切る。これが正典の「**全レア度で1も100も出る**」。
 *   切られるぶん、Aの平均は帯の中心23より上（表25.3）、Nは中心66より下（表64.9）へずれる。
 * ★ 掟：**分岐で呼び出し回数を変えない。**帯でも裾でも必ず3回引く
 */
/**
 * そのステの値が、**自分の帯のどこに居るか**を 0..1 で返す（帯の下端=0／上端=1）。
 * ★ 帯を入れた以上、ステを読む側の錨も帯へ移さないと意味がずれる。
 *   例：寿命はレア度A（帯 1〜45・平均25.3）。`40 + 30×(才能/100)` のままだと
 *   平均寿命が **47.6** になり、正典1504・確定事項A-6「40〜70歳・**平均55**」を割る。
 *   Q_DIVISOR 373→225 と `lifespanOf` の錨と**まったく同じ型**の直し。
 */
export function bandNorm(s, v) {
  const lo = BAND_LO[s], hi = BAND_HI[s];
  const x = (v - lo) / Math.max(1e-6, hi - lo);
  return x < 0 ? 0 : x > 1 ? 1 : x;
}
/** 帯の中心を 0 とした ±1 の位置（`(値−50)/50` の帯版） */
export function bandDev(s, v) { return bandNorm(s, v) * 2 - 1; }

export function drawBand(rng, s) {
  const lo = BAND_LO[s], hi = BAND_HI[s];
  const u = rng.next(), r2 = rng.next(), r3 = rng.next();
  if (u < BAND_IN) return lo + (hi - lo) * r2;
  // ★ 裾は **1..100 で打ち切った**指数分布（切り捨てではない）。
  //   切り捨てにすると 100ちょうどに山ができ、N のステで**4%の人が満点**になる
  //   （実測：95以上が 4.51%。正典の表は 0.64%）。打ち切りなら山ができない。
  //   逆関数で引くので**呼び出し回数は3回のまま**（掟：分岐で回数を変えない）
  const up = r2 >= 0.5;
  const room = up ? SCALE - hi : lo - 1;
  if (room <= 0) return up ? hi : lo;
  const cap = 1 - Math.exp(-room / BAND_TAU);
  const d = -BAND_TAU * Math.log(1 - r3 * cap);
  return up ? hi + d : lo - d;
}

