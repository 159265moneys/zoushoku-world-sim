// ---------------------------------------------------------------------------
// 国力（正典4-3）
// ---------------------------------------------------------------------------
// ★ 5項を同じ重みで混ぜる（重みは正典に無い・B-45）。
//   **混ぜた時点で構成が復元できなくなるのが機能**（正典2975）なので、
//   返すのは1つの数だけ。内訳は自国のぶんだけ別に返す（正典2978
//   「自分の国の内訳は完全に見える。相手のは見えない」）
export const POWER_BASE = {
  人口: 1000,        // この人数で1.000
  練度: 1,           // 平均の腕っぷし×練度。1.000 が基準
  耕地: 500,         // 畑の定員（人月）でこの値なら1.000
  産出率: 1,         // 産出/需要。1.000 が基準
  出産: 0.04,        // 年間出産数÷人口。正典7416「人口の約4%で固定」が基準
};

/**
 * 国力。★ **蓄え（蔵の中身・財）は入れない。**
 * @returns {{power:number, parts:object}} parts は**自国にだけ見せる**
 */
export function powerOf({ pop, skill, fieldCap, produced, demand, birthsPerYear }) {
  const parts = {
    人口: pop / POWER_BASE.人口,
    練度: skill / POWER_BASE.練度,
    耕地: fieldCap / POWER_BASE.耕地,
    産出率: demand > 0 ? (produced / demand) / POWER_BASE.産出率 : 0,
    出産: pop > 0 ? (birthsPerYear / pop) / POWER_BASE.出産 : 0,
  };
  let sum = 0, n = 0;
  for (const k of Object.keys(parts)) { sum += parts[k]; n++; }
  return { power: (sum / n) * 100, parts };   // 100 が「基準の国」
}

/** 応戦（正典2993）：**国力差 ±20% 以内なら受ける／格上からの宣戦は常に受ける** */
export function accepts(mine, theirs, bandPct = 20) {
  if (theirs > mine) return true;                       // 格上からは常に受ける
  return Math.abs(theirs - mine) <= mine * (bandPct / 100);
}

/** 順位階級（正典3297・3380・3742）：**上位1% ／ 以降10%刻み** */
export function rankBand(percentile) {
  if (percentile <= 0.01) return '上位1%';
  return `上位${Math.min(100, Math.ceil(percentile * 10) * 10)}%`;
}
